create policy "Users can read own profile" on public.profiles for select to authenticated
  using ((select auth.uid()) = id);

create policy "Public can read published stories" on public.stories for select
  using (status in ('in_progress', 'published', 'complete'));
create policy "Public can read genres" on public.genres for select using (true);
create policy "Public can read story genres" on public.story_genres for select
  using (
    exists (
      select 1 from public.stories
      where stories.id = story_genres.story_id
        and stories.status in ('in_progress', 'published', 'complete')
    )
    or (select public.is_admin())
  );
create policy "Public can read published chapters" on public.chapters for select
  using (
    exists (
      select 1 from public.stories
      where stories.id = chapters.story_id
        and stories.status in ('in_progress', 'published', 'complete')
    )
    or (select public.is_admin())
  );
create policy "Public can read published chapter media" on public.chapter_media for select
  using (
    exists (
      select 1
      from public.chapters
      join public.stories on stories.id = chapters.story_id
      where chapters.id = chapter_media.chapter_id
        and stories.status in ('in_progress', 'published', 'complete')
        and chapter_media.status = 'published'
    )
    or (select public.is_admin())
  );

create policy "Admins can manage stories" on public.stories for all to authenticated
  using ((select public.is_admin())) with check ((select public.is_admin()));
