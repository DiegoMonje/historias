create extension if not exists "pgcrypto";

do $$ begin
  create type public.story_status as enum ('draft', 'in_progress', 'published', 'complete');
exception
  when duplicate_object then null;
end $$;

do $$ begin
  create type public.media_status as enum ('pending', 'published', 'archived');
exception
  when duplicate_object then null;
end $$;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text,
  is_admin boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.stories (
  id uuid primary key default gen_random_uuid(),
  slug text not null unique,
  title text not null,
  eyebrow text,
  tagline text,
  synopsis text not null default '',
  author text not null default 'Ficción Oculta',
  status public.story_status not null default 'draft',
  year integer not null default extract(year from current_date)::integer,
  cover_url text,
  cover_prompt text,
  cover_alt text,
  cover_variant text not null default 'signal',
  cover_accent text not null default '#f1b75a',
  cover_ink text not null default '#071319',
  cover_code text not null default 'FO-01',
  total_reading_minutes integer not null default 0 check (total_reading_minutes >= 0),
  featured boolean not null default false,
  published_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.stories add column if not exists year integer not null default extract(year from current_date)::integer;
alter table public.stories add column if not exists cover_variant text not null default 'signal';
alter table public.stories add column if not exists cover_accent text not null default '#f1b75a';
alter table public.stories add column if not exists cover_ink text not null default '#071319';
alter table public.stories add column if not exists cover_code text not null default 'FO-01';
alter table public.stories alter column author set default 'Ficción Oculta';

create table if not exists public.genres (
  id bigint generated by default as identity primary key,
  slug text not null unique,
  name text not null unique
);

create table if not exists public.story_genres (
  story_id uuid not null references public.stories(id) on delete cascade,
  genre_id bigint not null references public.genres(id) on delete cascade,
  primary key (story_id, genre_id)
);

create table if not exists public.chapters (
  id uuid primary key default gen_random_uuid(),
  story_id uuid not null references public.stories(id) on delete cascade,
  number integer not null check (number > 0),
  title text not null,
  excerpt text,
  content jsonb not null default '[]'::jsonb,
  reading_minutes integer not null default 1 check (reading_minutes > 0),
  status public.story_status not null default 'draft',
  published_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (story_id, number)
);

create table if not exists public.chapter_media (
  id uuid primary key default gen_random_uuid(),
  chapter_id uuid not null references public.chapters(id) on delete cascade,
  sort_order integer not null default 0,
  after_block integer not null default 0 check (after_block >= 0),
  image_url text,
  alt_text text not null default '',
  generation_prompt text,
  aspect_ratio text not null default '16/9',
  status public.media_status not null default 'pending',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists chapters_story_number_idx on public.chapters (story_id, number);
create index if not exists chapter_media_chapter_order_idx on public.chapter_media (chapter_id, sort_order);

